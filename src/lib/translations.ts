export function getTranslation(key: string, lang: AppLanguage, ...args: any[]): string {
  let str = translations[lang]?.[key] || translations['EN']?.[key] || key;
  if (args.length > 0) {
    args.forEach((arg, i) => {
      str = str.replace(`%${i + 1}`, String(arg));
      str = str.replace('%s', String(arg));
      str = str.replace('%d', String(arg));
    });
  }
  return str;
}
